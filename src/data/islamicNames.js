/**
 * Günün tarihine göre deterministik bir offset üretir.
 * Her gün için farklı isim seçilir.
 */
function getDayOfYear(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - start.getTime();
  return Math.floor(diff / 86400000);
}

/**
 * Belirtilen sayıda isim döndürür.
 * Sıra: [kız, erkek, ...ekstra karışık]
 *
 * @param {number} limit 2-100 arası (default 2)
 * @returns {Array<{ id, name, arabic, meaning, gender, origin }>}
 */
export function getDailyNamePairs(limit = 2) {
  const clamped = Math.max(2, Math.min(100, Number(limit) || 2));
  const dayOfYear = getDayOfYear();

  const femaleList = ISLAMIC_NAMES.filter(
    (n) => n.gender === 'Kız',
  );
  const maleList = ISLAMIC_NAMES.filter(
    (n) => n.gender === 'Erkek',
  );

  // Boş liste güvenliği
  if (femaleList.length === 0 || maleList.length === 0) {
    return [];
  }

  const femalePick = femaleList[dayOfYear % femaleList.length];
  const malePick = maleList[dayOfYear % maleList.length];

  if (clamped <= 2) {
    return [femalePick, malePick].filter(Boolean);
  }

  // Ekstra isimleri karışık ekle
  const extras = [];
  const seen = new Set([femalePick?.id, malePick?.id]);
  const targetTotal = Math.min(clamped, ISLAMIC_NAMES.length);

  // Deterministik karışık seçim
  for (let i = 0; i < ISLAMIC_NAMES.length * 2; i++) {
    if (extras.length + 2 >= targetTotal) break;

    const candidate =
      ISLAMIC_NAMES[(dayOfYear * 3 + i) % ISLAMIC_NAMES.length];

    if (candidate && !seen.has(candidate.id)) {
      seen.add(candidate.id);
      extras.push(candidate);
    }
  }

  return [femalePick, malePick, ...extras].filter(Boolean);
}

/**
 * Tüm isimleri döndürür.
 */
export function getAllIslamicNames() {
  return [...ISLAMIC_NAMES];
}

/**
 * Cinsiyete göre filtreler.
 */
export function getNamesByGender(gender) {
  if (!gender) return [...ISLAMIC_NAMES];
  return ISLAMIC_NAMES.filter(
    (n) =>
      String(n.gender).toLocaleLowerCase('tr-TR') ===
      String(gender).toLocaleLowerCase('tr-TR'),
  );
}

/**
 * İsim veya anlamda arama yapar.
 */
export function searchIslamicNames(query) {
  const q = String(query ?? '')
    .toLocaleLowerCase('tr-TR')
    .trim();

  if (!q) return [];

  return ISLAMIC_NAMES.filter((n) => {
    const haystack = [
      n.name,
      n.meaning,
      n.arabic,
      n.origin,
    ]
      .filter(Boolean)
      .join(' ')
      .toLocaleLowerCase('tr-TR');

    return haystack.includes(q);
  });
}
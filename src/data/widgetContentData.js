/**
 * Belirli bir vakit için döngüsel olarak günün Ayet/Hadis/Dua içeriğini getirir.
 * @param {string} prayerId - imsak, sunrise, dhuhr, asr, maghrib, isha
 * @param {number} daySeed - Gün tohumu (opsiyonel, default: günün tarihi)
 */
export function getVakitCardContent(prayerId = 'dhuhr', daySeed = null) {
  const safeId = WIDGET_VAKIT_CONTENT[prayerId] ? prayerId : 'dhuhr';
  const pool = WIDGET_VAKIT_CONTENT[safeId];

  const now = new Date();
  const seed = daySeed != null
    ? Math.abs(Math.floor(daySeed))
    : (now.getFullYear() * 366 + (now.getMonth() + 1) * 31 + now.getDate());

  // Günün periyoduna göre tür seçimi: Ayet -> Hadis -> Dua dönüşümlü
  const kindIndex = seed % 3;
  if (kindIndex === 0) {
    const item = pool.ayetler[seed % pool.ayetler.length];
    return {
      type: 'ayet',
      badge: 'Vaktin Âyeti',
      icon: '📖',
      text: item.metin,
      source: item.kaynak,
    };
  } else if (kindIndex === 1) {
    const item = pool.hadisler[seed % pool.hadisler.length];
    return {
      type: 'hadis',
      badge: 'Vaktin Hadisi',
      icon: '🌙',
      text: item.metin,
      source: item.kaynak,
    };
  } else {
    const item = pool.dualar[seed % pool.dualar.length];
    return {
      type: 'dua',
      badge: 'Vaktin Duası',
      icon: '🤲',
      text: item.metin,
      source: item.kaynak,
    };
  }
}

/**
 * Belirli bir vakit için tüm içerik türlerinin rastgele karışık listesini döndürür.
 * Widget'ların farklı varyasyonları için kullanılabilir.
 * @param {string} prayerId - imsak, sunrise, dhuhr, asr, maghrib, isha
 * @param {number} count - Kaç adet içerik isteniyor (default 3)
 * @param {number} seed - Deterministik seçim için tohum (opsiyonel)
 */
export function getMixedVakitContent(prayerId = 'dhuhr', count = 3, seed = null) {
  const safeId = WIDGET_VAKIT_CONTENT[prayerId] ? prayerId : 'dhuhr';
  const pool = WIDGET_VAKIT_CONTENT[safeId];
  const now = new Date();
  const baseSeed = seed != null
    ? Math.abs(Math.floor(seed))
    : (now.getFullYear() * 366 + (now.getMonth() + 1) * 31 + now.getDate());

  const all = [
    ...pool.ayetler.map((i) => ({ ...i, type: 'ayet', badge: 'Vaktin Âyeti', icon: '📖' })),
    ...pool.hadisler.map((i) => ({ ...i, type: 'hadis', badge: 'Vaktin Hadisi', icon: '🌙' })),
    ...pool.dualar.map((i) => ({ ...i, type: 'dua', badge: 'Vaktin Duası', icon: '🤲' })),
  ];

  const result = [];
  const used = new Set();
  for (let i = 0; i < count && result.length < all.length; i++) {
    const idx = (baseSeed + i * 7) % all.length;
    if (!used.has(idx)) {
      used.add(idx);
      result.push({
        type: all[idx].type,
        badge: all[idx].badge,
        icon: all[idx].icon,
        text: all[idx].metin,
        source: all[idx].kaynak,
      });
    }
  }
  return result;
}

/**
 * Vakit için toplam içerik sayısını döndürür.
 * @param {string} prayerId
 */
export function getVakitContentCount(prayerId = 'dhuhr') {
  const safeId = WIDGET_VAKIT_CONTENT[prayerId] ? prayerId : 'dhuhr';
  const pool = WIDGET_VAKIT_CONTENT[safeId];
  return {
    ayetler: pool.ayetler.length,
    hadisler: pool.hadisler.length,
    dualar: pool.dualar.length,
    toplam: pool.ayetler.length + pool.hadisler.length + pool.dualar.length,
  };
}